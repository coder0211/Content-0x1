package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

const header = "# GENERATED by tools/openapi-bundle from api/openapi/*.yaml — DO NOT EDIT.\n"

func mapping(n *yaml.Node, key string) *yaml.Node {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

func ensure(n *yaml.Node, key string) *yaml.Node {
	if m := mapping(n, key); m != nil {
		return m
	}
	k := &yaml.Node{Kind: yaml.ScalarNode, Value: key}
	v := &yaml.Node{Kind: yaml.MappingNode}
	n.Content = append(n.Content, k, v)
	return v
}

func merge(dst, src *yaml.Node, where, file string) error {
	for i := 0; i+1 < len(src.Content); i += 2 {
		k := src.Content[i].Value
		if mapping(dst, k) != nil {
			return fmt.Errorf("%s: duplicate %s %q", file, where, k)
		}
		dst.Content = append(dst.Content, src.Content[i], src.Content[i+1])
	}
	return nil
}

// Bundle merges the fragments in dir.
func Bundle(dir string) ([]byte, error) {
	var base yaml.Node
	b, err := os.ReadFile(filepath.Join(dir, "_base.yaml"))
	if err != nil {
		return nil, err
	}
	if err := yaml.Unmarshal(b, &base); err != nil {
		return nil, fmt.Errorf("_base.yaml: %w", err)
	}
	root := base.Content[0]
	files, err := filepath.Glob(filepath.Join(dir, "*.yaml"))
	if err != nil {
		return nil, err
	}
	slices.Sort(files)
	for _, f := range files {
		name := filepath.Base(f)
		if name == "_base.yaml" {
			continue
		}
		var frag yaml.Node
		fb, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		if err := yaml.Unmarshal(fb, &frag); err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		if len(frag.Content) == 0 {
			continue
		}
		fr := frag.Content[0]
		for i := 0; i+1 < len(fr.Content); i += 2 {
			switch k := fr.Content[i].Value; k {
			case "paths":
				if err := merge(ensure(root, "paths"), fr.Content[i+1], "path", name); err != nil {
					return nil, err
				}
			case "components":
				comps := fr.Content[i+1]
				for j := 0; j+1 < len(comps.Content); j += 2 {
					section := comps.Content[j].Value
					if err := merge(ensure(ensure(root, "components"), section), comps.Content[j+1], "components."+section, name); err != nil {
						return nil, err
					}
				}
			default:
				return nil, fmt.Errorf("%s: only paths and components are allowed in fragments (found %q)", name, k)
			}
		}
	}
	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return nil, err
	}
	if err := checkRefs(root, buf.String()); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

var refRe = regexp.MustCompile(`\$ref: ['"]?#/components/([A-Za-z]+)/([A-Za-z0-9_.-]+)`)

// checkRefs fails on $refs to undefined components.
func checkRefs(root *yaml.Node, text string) error {
	comps := mapping(root, "components")
	var missing []string
	for _, m := range refRe.FindAllStringSubmatch(text, -1) {
		if mapping(mapping(comps, m[1]), m[2]) == nil {
			missing = append(missing, m[1]+"/"+m[2])
		}
	}
	if len(missing) > 0 {
		slices.Sort(missing)
		return fmt.Errorf("undefined $refs: %s", strings.Join(slices.Compact(missing), ", "))
	}
	return nil
}
