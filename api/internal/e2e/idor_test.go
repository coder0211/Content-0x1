package e2e

import (
	"fmt"
	"net/http"
	"slices"
	"testing"

	"github.com/be/acs/api/internal/shared/kernel"
)

// idorCase is one cross-user request that must be refused.
type idorCase struct {
	name   string
	token  string
	method string
	path   string
	body   any
	allow  []int // acceptable statuses (refusal); 404 preferred (no existence leak)
}

var refused = []int{http.StatusNotFound, http.StatusForbidden}

// TestIDOR (ACS-100): creator A owns a campaign, content assets, an image
// asset, a video project, an upload and jobs; creator B (no membership) and
// a reviewer try to read or change them through every resource-scoped
// endpoint. All attempts must be refused (404, or 403 where the resource is
// legitimately visible but not modifiable), and the owners' data must stay
// untouched. Lead/Admin access is asserted where SPEC-04 grants it.
func TestIDOR(t *testing.T) {
	w := newWorld(t)
	a, b, rv := kernel.RoleContentCreator, kernel.RoleContentCreator+"2", kernel.RoleReviewer
	brandID, productID := w.seedBrand()
	campA := w.seedCampaign(a, brandID, productID)
	campB := w.seedCampaign(b, brandID, productID)
	jobA, assets := w.generateContent(a, campA, brandID, productID, 1)
	assetA := assets[0]

	// A's upload (pending file).
	var up struct {
		FileID kernel.ID `json:"file_id"`
	}
	w.must(http.StatusCreated, a, "POST", "/files/upload-url", map[string]any{
		"filename": "ref.png", "mime_type": "image/png", "size_bytes": 1024, "purpose": "reference_image"}, &up)

	// A's image asset (generated by the fake provider).
	var imgAcc struct {
		JobID kernel.ID `json:"job_id"`
	}
	w.must(http.StatusAccepted, a, "POST", "/images/generations", map[string]any{
		"campaign_id": campA, "prompt": "Poster khóa học", "preset": "poster", "aspect_ratio": "1:1", "quality": "standard", "count": 1,
	}, &imgAcc)
	w.runJobs()
	var imgJob struct {
		Status string         `json:"status"`
		Result map[string]any `json:"result"`
		Error  any            `json:"error"`
	}
	w.must(http.StatusOK, a, "GET", "/jobs/"+imgAcc.JobID.String(), nil, &imgJob)
	if imgJob.Status != "succeeded" {
		t.Fatalf("image job %s %v", imgJob.Status, imgJob.Error)
	}
	imageAsset := fmt.Sprint(imgJob.Result["asset_id"])
	imageFile := fmt.Sprint(imgJob.Result["file_ids"].([]any)[0])

	// A's video project (storyboard job only).
	var vid struct {
		AssetID kernel.ID `json:"asset_id"`
	}
	w.must(http.StatusAccepted, a, "POST", "/videos", map[string]any{
		"campaign_id": campA, "prompt": "Video quảng cáo khóa học", "preset": "social_vertical", "target_duration_seconds": 12,
	}, &vid)
	w.runJobs()
	videoA := vid.AssetID.String()

	cases := []idorCase{
		// Assets: library read is open to brand.view, changes are owner/lead only.
		{"asset patch", b, "PATCH", "/assets/" + assetA.String(), map[string]any{"title": "hijack"}, refused},
		{"asset delete", b, "DELETE", "/assets/" + assetA.String(), nil, refused},
		{"asset new version", b, "POST", "/assets/" + assetA.String() + "/versions", map[string]any{"content_json": map[string]any{"title": "x", "body_text": "x"}, "change_note": "x", "base_version_no": 1}, refused},
		{"asset restore", b, "POST", "/assets/" + assetA.String() + "/versions/1/restore", map[string]any{}, refused},
		{"asset submit-review", b, "POST", "/assets/" + assetA.String() + "/submit-review", map[string]any{}, refused},
		{"asset download (draft, creator)", b, "POST", "/assets/" + assetA.String() + "/download-url", map[string]any{}, refused},
		{"asset download (draft, reviewer)", rv, "POST", "/assets/" + assetA.String() + "/download-url", map[string]any{}, refused},
		{"reviewer edits asset", rv, "PATCH", "/assets/" + assetA.String(), map[string]any{"title": "x"}, refused},
		{"content rewrite", b, "POST", "/content/" + assetA.String() + "/rewrites", map[string]any{"instruction": "shorten"}, refused},
		{"content generation in A's campaign", b, "POST", "/content/generations", map[string]any{
			"campaign_id": campA, "brand_id": brandID, "platform": "facebook", "content_type": "promotional_post", "objective": "lead",
			"framework": "PAS", "length": "medium", "language": "vi", "tone": []string{"friendly"},
			"brief": map[string]any{"product_id": productID, "target_audience": "x", "key_message": "x", "cta": "x"}, "variants": 1}, refused},
		// Campaigns.
		{"campaign patch", b, "PATCH", "/campaigns/" + campA.String(), map[string]any{"name": "hijack"}, refused},
		{"campaign plan", b, "PUT", "/campaigns/" + campA.String() + "/plan", map[string]any{"plan": map[string]any{"summary": "x", "themes": []string{}, "items": []map[string]any{{"topic": "x", "format": "post"}}}}, refused},
		{"campaign plan-generation", b, "POST", "/campaigns/" + campA.String() + "/plan-generations", map[string]any{}, refused},
		{"campaign discard proposal", b, "DELETE", "/campaigns/" + campA.String() + "/plan-proposal", nil, refused},
		// Files: owner only, 404.
		{"file get", b, "GET", "/files/" + up.FileID.String(), nil, []int{http.StatusNotFound}},
		{"file complete", b, "POST", "/files/" + up.FileID.String() + "/complete", map[string]any{}, []int{http.StatusNotFound}},
		{"generated file get", b, "GET", "/files/" + imageFile, nil, []int{http.StatusNotFound}},
		{"reviewer file get", rv, "GET", "/files/" + up.FileID.String(), nil, []int{http.StatusNotFound}},
		// Jobs: owner or provider.view, else 404.
		{"job get", b, "GET", "/jobs/" + jobA.String(), nil, []int{http.StatusNotFound}},
		{"job events", b, "GET", "/jobs/" + jobA.String() + "/events", nil, []int{http.StatusNotFound}},
		{"job history", b, "GET", "/jobs/" + jobA.String() + "/history", nil, []int{http.StatusNotFound}},
		{"job cancel", b, "POST", "/jobs/" + jobA.String() + "/cancel", map[string]any{}, []int{http.StatusNotFound}},
		{"job retry", b, "POST", "/jobs/" + jobA.String() + "/retry", map[string]any{}, []int{http.StatusNotFound}},
		{"job get (reviewer)", rv, "GET", "/jobs/" + jobA.String(), nil, []int{http.StatusNotFound}},
		// Images.
		{"image edit", b, "POST", "/images/" + imageAsset + "/edits", map[string]any{"file_id": imageFile, "prompt": "x"}, refused},
		{"image variations", b, "POST", "/images/" + imageAsset + "/variations", map[string]any{"file_id": imageFile, "count": 1}, refused},
		{"image generation with A's upload", b, "POST", "/images/generations", map[string]any{
			"campaign_id": campB, "prompt": "x", "preset": "poster", "aspect_ratio": "1:1", "quality": "standard", "count": 1,
			"reference_file_ids": []string{imageFile}}, refused},
		// Videos.
		{"video scenes", b, "PUT", "/videos/" + videoA + "/scenes", map[string]any{"scenes": []any{}}, refused},
		{"video estimate", b, "POST", "/videos/" + videoA + "/estimate", map[string]any{}, refused},
		{"video production", b, "POST", "/videos/" + videoA + "/productions", map[string]any{}, refused},
		{"video render", b, "POST", "/videos/" + videoA + "/renders", map[string]any{}, refused},
		{"video scene regeneration", b, "POST", "/videos/" + videoA + "/scenes/" + kernel.NewID().String() + "/regenerations", map[string]any{}, refused},
		{"video from A's image file", b, "POST", "/videos", map[string]any{
			"campaign_id": campB, "source": map[string]any{"type": "image", "file_ids": []string{imageFile}}, "prompt": "x",
			"preset": "social_vertical", "target_duration_seconds": 12}, []int{http.StatusBadRequest, http.StatusNotFound, http.StatusForbidden}}, // 400 source.file_ids[0]=not_found (no existence leak)
		{"video in A's campaign", b, "POST", "/videos", map[string]any{
			"campaign_id": campA, "prompt": "x", "preset": "social_vertical", "target_duration_seconds": 12}, []int{http.StatusForbidden}},
		{"image generation in A's campaign", b, "POST", "/images/generations", map[string]any{
			"campaign_id": campA, "prompt": "x", "preset": "poster", "aspect_ratio": "1:1", "quality": "standard", "count": 1}, []int{http.StatusForbidden}},
	}
	before, _ := w.assets.Get(t.Context(), assetA)
	for _, c := range cases {
		rec := w.call(c.token, c.method, c.path, c.body, nil)
		if !slices.Contains(c.allow, rec.Code) {
			t.Errorf("IDOR %s: %s %s as %s → %d %s (want one of %v)", c.name, c.method, c.path, c.token, rec.Code, rec.Body.String(), c.allow)
		} else {
			t.Logf("refused %-36s %s %s → %d", c.name, c.method, c.path, rec.Code)
		}
	}
	after, _ := w.assets.Get(t.Context(), assetA)
	if after.Title != before.Title || after.Status != before.Status || after.CurrentVersion.VersionNo != before.CurrentVersion.VersionNo {
		t.Fatalf("asset changed by other users: %+v → %+v", before, after)
	}

	// Job list never shows other users' jobs; provider.view (lead) sees them.
	var listB []struct {
		ID kernel.ID `json:"id"`
	}
	w.must(http.StatusOK, b, "GET", "/jobs", nil, &listB)
	for _, j := range listB {
		if j.ID == jobA {
			t.Fatal("B's job list contains A's job")
		}
	}
	w.must(http.StatusOK, kernel.RoleMarketingLead, "GET", "/jobs/"+jobA.String(), nil, nil)
	w.must(http.StatusOK, kernel.RoleAdmin, "GET", "/files/"+up.FileID.String(), nil, nil)
	// Lead may download a draft (ACS-084); owner sees own file/job.
	w.must(http.StatusOK, kernel.RoleMarketingLead, "POST", "/assets/"+assetA.String()+"/download-url", map[string]any{}, nil)
	w.must(http.StatusOK, a, "GET", "/files/"+up.FileID.String(), nil, nil)
	w.must(http.StatusOK, a, "GET", "/jobs/"+jobA.String(), nil, nil)
	// Positive controls: the refused endpoints work for the owner, so the
	// refusals above are access decisions, not broken fixtures.
	w.must(http.StatusOK, a, "POST", "/videos/"+videoA+"/estimate", map[string]any{}, nil)
	w.must(http.StatusAccepted, a, "POST", "/images/"+imageAsset+"/variations", map[string]any{"file_id": imageFile, "count": 1}, nil)
	w.must(http.StatusAccepted, a, "POST", "/content/"+assetA.String()+"/rewrites", map[string]any{"instruction": "shorten"}, nil)
	w.must(http.StatusAccepted, a, "POST", "/campaigns/"+campA.String()+"/plan-generations", map[string]any{}, nil)
	w.must(http.StatusOK, a, "PATCH", "/assets/"+assetA.String(), map[string]any{"title": "Tiêu đề mới"}, nil)
}
